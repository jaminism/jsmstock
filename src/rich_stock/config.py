    entry_valid_days: int = 3
    """원문 §2-5 "매수 가능 기간은 **고점 갱신일 포함 4일차까지**로 제한한다(그 이후는 기법
    유효성 상실로 간주)"를 반영. 진입 탐색이 상한가 당일 다음날부터 시작하므로(D+1~D+3) 고점
    갱신일을 포함하면 총 4일이 된다.

    **2026-09-05 정정**: 그전까지 이 값을 오버라이드하지 않아 PortfolioConfig 기본값 7(S1의
    "상한가 후 7일" 규칙)을 쓰고 있었다 — 원문과 다른 창으로 백테스트하고 있었다는 뜻이다.
    같은 문구를 쓰는 S5는 4로 정확히 구현돼 있었고 S2도 "D+1·D+2"를 2로 반영했는데 S3만
    누락됐다. 실측(캐시 2,713종목, 0% 슬리피지)으로도 원문 쪽이 낫다: 7일 → 780건
    CAGR+18.51% MDD-17.61% PF2.03 / 3일 → 408건 CAGR+17.04% MDD-11.18% PF2.46 —
    거래는 절반인데 낙폭이 작고 수익성이 좋아, 원문의 "그 이후는 유효성 상실" 주장이
    실측으로 지지된다."""

    pre_rally_lookback_days: int = 5
    """되돌림 기준 저점(DLL) 산출용 lookback. 원문 5분봉 기준 "상한가 직전 RSI 과매도 지점"을
    일봉 데이터만으로는 재현할 수 없어(장중 데이터 부재), 상한가 발생일을 포함해 그 이전
    5거래일(원문 DLL 수식의 npredaylow(1)~(5) 범위와 동일한 폭) 중 최저가를 저점 기준으로 근사한다.
    **이 저점은 상한가 발생 시점에 한 번 고정되며, 이후 눌림에 따라 갱신되지 않는다** — S1의
    R0~R3 그리드가 상한가 당일 값으로 고정되는 것과 동일한 방식으로 단순화했다. (초기 구현은
    상한가 이후의 롤링 최저가를 저점으로 썼으나, 이 경우 상한가 다음날 어떤 하락이든 정의상
    항상 그날 자신의 저가가 되돌림선을 트리거하는 자기순환적 문제가 있어 폐기했다.)"""

    stop_loss_pct: float = -0.07
    """(신규 설계) 진입가 대비 -7% 하락 시 손절. 원문에 없음 — step_3(S2)/step_5(S45) 문서의
    '-7% 하락시 추매(대장주) 또는 손절(그 외)' 패턴에서, 1등주 판정을 자동화할 수 없다는 한계상
    '그 외' 케이스(손절)로 통일해 차용했다. 추매 로직은 이번 버전에 구현하지 않는다."""


